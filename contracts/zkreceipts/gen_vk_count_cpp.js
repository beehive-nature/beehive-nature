// gen_vk_count_cpp.js — vk.json → vk_count_constants.hpp for count.circom's
// verifier (copy of ../privacy/gen_vk_cpp.js with ONLY the provenance lines
// and defaults changed — the byte-level logic is the M4-lane's, tested by
// its gates; decimal byte arrays per the repo's hex-run law; projective →
// affine; G2 word order EIP-197).
const fs = require('fs');
const vk = JSON.parse(fs.readFileSync(process.argv[2] || '/home/travi/plonkport/count_vk.json', 'utf8'));
if (vk.protocol !== 'plonk' || vk.curve !== 'bn128') throw new Error('not a bn128 plonk vk');

const Q  = 21888242871839275222246405745257275088548364400416034343698204186575808495617n; // PUBLIC-CONSTANT BN254 scalar field
const QF = 21888242871839275222246405745257275088696311157297823662689037894645226208583n; // PUBLIC-CONSTANT BN254 base field
const G2GEN = [ // PUBLIC-CONSTANT BN254 G2 generator, [x_c0, x_c1, y_c0, y_c1]
  10857046999023057135944570762232829481370756359578518086990519993285655852781n,   // PUBLIC-CONSTANT public chain constant / test vector (hex-run law)
  11559732032986387107991004021392285783925812861821192530917403151452391805634n,   // PUBLIC-CONSTANT public chain constant / test vector (hex-run law)
  8495653923123431417604973247489272438418190587263600148770280649306958101930n,   // PUBLIC-CONSTANT public chain constant / test vector (hex-run law)
  4082367875863433681332203403145435568316851327593401208105741076214120093531n,   // PUBLIC-CONSTANT public chain constant / test vector (hex-run law)
];

const be = (v, n) => { const b = []; for (let i = n - 1; i >= 0; --i) b.push(Number((v >> BigInt(8 * i)) & 255n)); return b; };
const decArr = (bytes, per) => {
   const parts = [];
   for (let i = 0; i < bytes.length; i += per) parts.push('   ' + bytes.slice(i, i + per).join(',') + ',');
   return '\n' + parts.join('\n');
};
const inv = (a, m) => {
   let t = 0n, nt = 1n, r = m, nr = a % m;
   while (nr) { const q = r / nr; [t, nt] = [nt, t - q * nt]; [r, nr] = [nr, r - q * nr]; }
   if (t < 0n) t += m; return t;
};
const affine = (p, m) => {
   let [x, y, z] = [BigInt(p[0]), BigInt(p[1]), BigInt(p[2] ?? 1n)];
   if (z !== 1n) { const zi = inv(z % m, m); x = x * zi % m; y = y * zi % m; }
   return [x % m, y % m];
};

const P = v => { const [x, y] = affine(v, QF); return be(x, 32).concat(be(y, 32)); };
const S = v => be(BigInt(v) % Q, 32);
const g2 = ([c0x, c1x, c0y, c1y]) => be(c1x, 32).concat(be(c0x, 32), be(c1y, 32), be(c0y, 32));

const h = [];
h.push('// vk_count_constants.hpp — GENERATED by gen_vk_count_cpp.js from count_vk.json. DO NOT EDIT BY HAND.');
h.push('// Provenance: circuit count.circom (64-leaf full-tree Poseidon count fold,');

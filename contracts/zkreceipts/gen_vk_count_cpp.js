h.push('// honest participant (rehearsal seat, 2026-10-06), snarkjs 0.7.6 plonk setup,');
h.push('// nPublic ' + vk.nPublic + ' (root, kind, count).');
h.push('// Regenerate: node gen_vk_count_cpp.js /path/to/vk.json vk_count_constants.hpp');
h.push('#pragma once');
h.push('');
h.push('static constexpr int N_PUBLIC = ' + vk.nPublic + ';');
h.push('static constexpr int PL_POWER = ' + vk.power + ';   // n = 2^PL_POWER rows');
h.push('');
for (const [k, v] of [['QM', vk.Qm], ['QL', vk.Ql], ['QR', vk.Qr], ['QO', vk.Qo], ['QC', vk.Qc], ['S1', vk.S1], ['S2', vk.S2], ['S3', vk.S3]]) {
   h.push('static constexpr unsigned char VK_' + k + '[64] = {' + decArr(P(v), 16) + '\n};');
   h.push('');
}
h.push('static constexpr unsigned char VK_X2[128] = {' + decArr(g2([BigInt(vk.X_2[0][0]), BigInt(vk.X_2[0][1]), BigInt(vk.X_2[1][0]), BigInt(vk.X_2[1][1])]).map(x => x), 16) + '\n};');
h.push('');
h.push('static constexpr unsigned char VK_W1[32] = {' + decArr(S(vk.w), 16) + '\n};');
h.push('static constexpr unsigned char VK_K1[32] = {' + decArr(S(vk.k1), 16) + '\n};');
h.push('static constexpr unsigned char VK_K2[32] = {' + decArr(S(vk.k2), 16) + '\n};');
h.push('');
h.push('// chain constants (independent of the vk)');
h.push('static constexpr unsigned char PL_Q[32] = {' + decArr(be(Q, 32), 16) + '\n};');
h.push('static constexpr unsigned char PL_QF[32] = {' + decArr(be(QF, 32), 16) + '\n};');
h.push('static constexpr unsigned char PL_G1GEN[64] = {' + decArr(be(1n, 32).concat(be(2n, 32)), 16) + '\n};');
h.push('static constexpr unsigned char PL_G2GEN[128] = {' + decArr(g2(G2GEN), 16) + '\n};');
h.push('');
fs.writeFileSync(process.argv[3] || 'vk_count_constants.hpp', h.join('\n'));
console.log('vk_count_constants.hpp written: power', vk.power, 'nPublic', vk.nPublic);

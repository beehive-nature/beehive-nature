// gen_poseidon_cpp.js — circomlib's Poseidon (t=3, nInputs=2) → poseidon2.hpp
// (C++ over field256, Montgomery-domain constants) + tree_zeros.hpp (the
// depth-20 zero chain for the ON-CHAIN incremental tree) + cross-vectors
// from circomlibjs for the native gate.
//
// Single source of truth: the constants are PARSED from circomlib's own
// poseidon_constants.circom (t==3 blocks) — never retyped by hand. The
// structure mirrors poseidon.circom's PoseidonEx(nInputs=2, 1): initial
// state (0, in0, in1); 3 full rounds (σ+Ark+Mix M); a middle round with the
// P matrix; 57 partial rounds (σ on state[0] with the Ark constant folded,
// then the sparse S-matrix MixS); 3 more full rounds; final σ + MixLast
// (M row 0). Round constant layout: C[0..2] ark0; C[3..11] first half;
// C[12..14] middle; C[15..71] partial (folded); C[72..80] second half.
const fs = require('fs');

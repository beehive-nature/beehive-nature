   const R = (1n << 256n) % QR;
   const toMont = hex => '0x' + ((BigInt(hex) * R) % QR).toString(16);

   const hpp = [];
   hpp.push('// poseidon2.hpp — GENERATED by gen_poseidon_cpp.js from circomlib\'s');
   hpp.push('// poseidon_constants.circom (t==3). DO NOT EDIT BY HAND. Round structure');
   hpp.push('// mirrors poseidon.circom PoseidonEx(2,1) verbatim (see the generator');
   hpp.push('// header for the round/constant layout). Constants are stored');
   hpp.push('// PRE-CONVERTED to Montgomery form (v·R mod q, M8) — poseidon2_ctx_init');
   hpp.push('// does NO constant work; the t=3 instance is bound to the BN254 scalar');
   hpp.push('// field (the mont conversion is modulus-specific by construction).');
   hpp.push('// COMPATIBILITY GATE: test_poseidon.cpp checks this implementation');
   hpp.push('// against circomlibjs on ' + vectors.length + ' vectors BEFORE any chain use.');

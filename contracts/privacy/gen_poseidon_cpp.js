   hpp.push(arr256('POSE_S', S.map(toMont)));
   hpp.push(`
// ── the t=3 instance. M8: the ctx is the BARE field context — every round
// constant above is already Montgomery-form; init does ZERO constant work. ──
struct poseidon2_ctx {
   fctx fq;
};

static void poseidon2_ctx_init( poseidon2_ctx* pc, const unsigned char q_be[32] ) {
   u256 q; f256_from_be( q, q_be );
   fctx_init( &pc->fq, q );   // must be the BN254 scalar field (the constants are bound to it)
}

// σ(x) = x⁵ entirely in Montgomery form: MM(x,x)=x²R, MM(x²,x²)=x⁴R, MM(x⁴,x)=x⁵R
static inline void p2_sigma( const fctx* f, const u256 x, u256 out ) {
   u256 x2, x4;
   mont_mul( f, x, x, x2 );
   mont_mul( f, x2, x2, x4 );
   mont_mul( f, x4, x, out );
}
// st[i] = Σ_j M[j][i]·s[j]  (constants Montgomery-form ⇒ result stays in form)
static inline void p2_matvec( const fctx* f, const u256 mrow[9], const u256 s[3], u256 st[3] ) {
   u256 t0, t1, t2;
   mont_mul( f, s[0], mrow[0], t0 ); mont_mul( f, s[1], mrow[3], t1 ); mont_mul( f, s[2], mrow[6], t2 );
   f_add( f, t0, t1, t0 ); f_add( f, t0, t2, st[0] );
   mont_mul( f, s[0], mrow[1], t0 ); mont_mul( f, s[1], mrow[4], t1 ); mont_mul( f, s[2], mrow[7], t2 );
   f_add( f, t0, t1, t0 ); f_add( f, t0, t2, st[1] );
   mont_mul( f, s[0], mrow[2], t0 ); mont_mul( f, s[1], mrow[5], t1 ); mont_mul( f, s[2], mrow[8], t2 );
   f_add( f, t0, t1, t0 ); f_add( f, t0, t2, st[2] );
}

// out = H(a, b) — circomlib Poseidon(2)
static void poseidon2( const poseidon2_ctx* pc, const u256 a, const u256 b, u256 out ) {
   const fctx* f = &pc->fq;
   u256 st[3], s[3], t1, t2, t3;
   // initial state (0, a, b), ark[0]
   f256_zero( st[0] );
   mont_mul( f, a, f->r2, st[1] ); mont_mul( f, b, f->r2, st[2] );
   f_add( f, st[0], POSE_C[0], st[0] ); f_add( f, st[1], POSE_C[1], st[1] ); f_add( f, st[2], POSE_C[2], st[2] );
   // first half: 3 full rounds (σ + ark C[3..11] + Mix M)
   for ( int r = 0; r < 3; ++r ) {
      for ( int j = 0; j < 3; ++j ) { p2_sigma( f, st[j], s[j] ); f_add( f, s[j], POSE_C[3*(r+1)+j], s[j] ); }
      p2_matvec( f, POSE_M, s, st );
   }
   // middle round: σ + ark C[12..14] + Mix P
   for ( int j = 0; j < 3; ++j ) { p2_sigma( f, st[j], s[j] ); f_add( f, s[j], POSE_C[12+j], s[j] ); }
   p2_matvec( f, POSE_P, s, st );
   // 57 partial rounds: σ(state[0]) + folded C[15+r], sparse MixS with S
   for ( int r = 0; r < 57; ++r ) {
      p2_sigma( f, st[0], t1 );
      f_add( f, t1, POSE_C[15 + r], t1 );
      // out0 = Σ S[5r+i]·in_i ; out_i = in_i + in_0·S[5r+2+i]
      mont_mul( f, t1, POSE_S[5*r+0], t2 );
      u256 t4; mont_mul( f, st[1], POSE_S[5*r+1], t3 ); f_add( f, t2, t3, t2 );
      u256 t5; mont_mul( f, st[2], POSE_S[5*r+2], t4 ); f_add( f, t2, t4, t5 );   // new0
      u256 n1, n2;
      mont_mul( f, t1, POSE_S[5*r+3], t2 ); f_add( f, st[1], t2, n1 );
      mont_mul( f, t1, POSE_S[5*r+4], t2 ); f_add( f, st[2], t2, n2 );
      f256_copy( st[0], t5 ); f256_copy( st[1], n1 ); f256_copy( st[2], n2 );
   }
   // second half: 3 full rounds (σ + ark C[72..80] + Mix M)
   for ( int r = 0; r < 3; ++r ) {
      for ( int j = 0; j < 3; ++j ) { p2_sigma( f, st[j], s[j] ); f_add( f, s[j], POSE_C[72+3*r+j], s[j] ); }
      p2_matvec( f, POSE_M, s, st );
   }
   // final: σ on all + MixLast (M row 0)
   u256 acc, one;
   f256_set_u64( one, 1 );
   f256_zero( acc );
   for ( int j = 0; j < 3; ++j ) {
      p2_sigma( f, st[j], s[j] );
      u256 t; mont_mul( f, s[j], POSE_M[3*j], t );   // M[j][0] — flat layout m[j*3+0]
      f_add( f, acc, t, acc );
   }
   mont_mul( f, acc, one, out );                  // leave Montgomery form
}
`);
   fs.writeFileSync(process.argv[2] || 'poseidon2.hpp', hpp.join('\n'));


   for (let i = 1; i <= 20; i++) zeros.push(H(zeros[i - 1], zeros[i - 1]));

   const w32 = v => BigInt(v).toString(16).padStart(64, '0');
   const vectors = [];
   const rnd = () => BigInt('0x' + require('crypto').randomBytes(30).toString('hex'));
   vectors.push(['0', '0', H(0, 0)]);
   vectors.push(['1', '0', H(1, 0)]);
   vectors.push(['0', '1', H(0, 1)]);
   vectors.push(['18446744073709551615', '1', H('18446744073709551615', '1')]);   // 2^64−1 edge
   for (let i = 0; i < 60; i++) { const a = rnd(), b = rnd(); vectors.push([a.toString(), b.toString(), H(a.toString(), b.toString())]); }
   // tree-shaped vectors: consecutive zero-chain hashes
   vectors.push([zeros[0], zeros[0], zeros[1]]);
   vectors.push([zeros[19], zeros[19], zeros[20]]);


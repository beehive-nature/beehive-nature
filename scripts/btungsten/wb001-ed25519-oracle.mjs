// wb001-ed25519-oracle.mjs — pins Ed25519 signatures from an INDEPENDENT
// implementation (node:crypto, i.e. OpenSSL) so the Rust model's signer
// (libcrux-ed25519, HACL*-verified) and the Cryptol RFC 8032 spec
// (wb001-cryptol/Ed25519.cry) are each compared against a third party,
// never against themselves.
//
// Rows: the four RFC 8032 §7.1 Ed25519 vectors (transcribed below from the
// RFC; this script refuses to write if OpenSSL does not reproduce them,
// so the oracle is checked before it is trusted), then every positive
// envelope of wb001-vectors.json signed under the TEST 1 and TEST 3 seeds.
//
// usage: node wb001-ed25519-oracle.mjs [--check]
import { createPrivateKey, createPublicKey, sign } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const RFC8032 = [
  { name: 'RFC8032 TEST 1', seed: '9d61b19deffd5a60ba844af492ec2cc44449c5697b326919703bac031cae7f60', pk: 'd75a980182b10ab7d54bfed3c964073a0ee172f3daa62325af021a68f707511a', msg: '', sig: 'e5564300c360ac729086e2cc806e828a84877f1eb8e5d974d873e065224901555fb8821590a33bacc61e39701cf9b46bd25bf5f0595bbe24655141438e7a100b' }, // PUBLIC-CONSTANT: RFC 8032 test vector
  { name: 'RFC8032 TEST 2', seed: '4ccd089b28ff96da9db6c346ec114e0f5b8a319f35aba624da8cf6ed4fb8a6fb', pk: '3d4017c3e843895a92b70aa74d1b7ebc9c982ccf2ec4968cc0cd55f12af4660c', msg: '72', sig: '92a009a9f0d4cab8720e820b5f642540a2b27b5416503f8fb3762223ebdb69da085ac1e43e15996e458f3613d0f11d8c387b2eaeb4302aeeb00d291612bb0c00' }, // PUBLIC-CONSTANT: RFC 8032 test vector
  { name: 'RFC8032 TEST 3', seed: 'c5aa8df43f9f837bedb7442f31dcb7b166d38535076f094b85ce3a2e0b4458f7', pk: 'fc51cd8e6218a1a38da47ed00230f0580816ed13ba3303ac5deb911548908025', msg: 'af82', sig: '6291d657deec24024827e69c3abe01a30ce548a284743a445e3680d7db5ac3ac18ff9b538d16f290ae67f760984dc6594a7c15e9716ed28dc027beceea1ec40a' }, // PUBLIC-CONSTANT: RFC 8032 test vector
  { name: 'RFC8032 TEST SHA(abc)', seed: '833fe62409237b9d62ec77587520911e9a759cec1d19755b7da901b96dca3d42', pk: 'ec172b93ad5e563bf4932c70e1245034c35467ef2efd4d64ebf819683467e2bf', msg: 'ddaf35a193617abacc417349ae20413112e6fa4e89a97ea20a9eeee64b55d39a2192992a274fc1a836ba3c23a3feebbd454d4423643ce80e2a9ac94fa54ca49f', sig: 'dc2a4459e7369633a52b1bf277839a00201009a3efbf3ecb69bea2186c26b58909351fc9ac90b3ecfdfbc7c66431e0303dca179c138ac17ad9bef1177331a704' }, // PUBLIC-CONSTANT: RFC 8032 test vector
];

const PKCS8_PREFIX = Buffer.from('302e020100300506032b657004220420', 'hex'); // PUBLIC-CONSTANT: DER header of an Ed25519 PKCS#8 key
const keyOf = (seedHex) => createPrivateKey({ key: Buffer.concat([PKCS8_PREFIX, Buffer.from(seedHex, 'hex')]), format: 'der', type: 'pkcs8' });
const pkOf = (seedHex) => createPublicKey(keyOf(seedHex)).export({ format: 'der', type: 'spki' }).subarray(-32).toString('hex');
const sigOf = (seedHex, msgHex) => sign(null, Buffer.from(msgHex, 'hex'), keyOf(seedHex)).toString('hex');

for (const v of RFC8032) {
  if (pkOf(v.seed) !== v.pk) throw new Error(`${v.name}: OpenSSL public key disagrees with the RFC — oracle not trusted`);
  if (sigOf(v.seed, v.msg) !== v.sig) throw new Error(`${v.name}: OpenSSL signature disagrees with the RFC — oracle not trusted`);
}

const vectors = JSON.parse(readFileSync(new URL('./wb001-vectors.json', import.meta.url), 'utf8'));
const rows = RFC8032.map((v) => ({ name: v.name, seed: v.seed, pk: v.pk, msg: v.msg, sig: v.sig }));
for (const seedRow of [RFC8032[0], RFC8032[2]]) {
  for (const p of vectors.positives) {
    rows.push({ name: `${p.name} under ${seedRow.name} seed`, seed: seedRow.seed, pk: seedRow.pk, msg: p.envelope, sig: sigOf(seedRow.seed, p.envelope) });
  }
}

const doc = {
  what: 'PUBLIC-CONSTANT: Ed25519 signatures from node:crypto (OpenSSL), an implementation independent of the Rust model and the Cryptol spec; RFC 8032 public test seeds only; generated by wb001-ed25519-oracle.mjs, never by hand.',
  oracle: `node ${process.version} / OpenSSL ${process.versions.openssl}`,
  rows,
};
const text = JSON.stringify(doc) + '\n';
const path = new URL('./wb001-ed25519-oracle.json', import.meta.url);
if (process.argv.includes('--check')) {
  const have = JSON.parse(readFileSync(path, 'utf8'));
  const same = JSON.stringify(have.rows) === JSON.stringify(doc.rows);
  console.log(same ? `bT-WB001-ed25519: oracle --check identical across ${rows.length} rows` : 'bT-WB001-ed25519: oracle DRIFT');
  process.exit(same ? 0 : 1);
}
writeFileSync(path, text);
console.log(`bT-WB001-ed25519: oracle pinned 0 -> ${rows.length} rows (${RFC8032.length} RFC 8032 reproduced first)`);

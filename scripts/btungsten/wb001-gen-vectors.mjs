// wb001-gen-vectors.mjs — regenerate scripts/btungsten/wb001-vectors.json
// from the current module. The file is PINNED once generated; every twin
// (Rust, Cryptol) must reproduce the positives byte-for-byte and the
// refusals by code before any equivalence claim (founder ruling
// 2026-10-07). Run after an INTENTIONAL format change only — the battery
// re-derives and compares every row on every CI run.
import { writeFileSync } from 'node:fs';
import { canonical, MAGIC, VERSION } from './wb001-intent.mjs';

const b32 = (seed) => { const b = Buffer.alloc(32); b.write(seed.slice(0, 24), 0, 'utf8'); return b; };
const base = () => ({
  domain: 'skaists.bpay/1',
  nonce: b32('nonce-wb001'),
  epoch: 1n,
  action: b32('action-hash-01'),
  destination: 'vault:0xBEEF',
  capability: 'pay',
  amount: 1000000n,
  expiry: 1790000000n,
  payer: 'seat:bFUzZ',
  payload: Buffer.from('{"upload_id":"up-1"}', 'utf8'),
});
const withDomainBytes = (bytes) => {
  const rest = canonical(base()).subarray(8 + 5 + Buffer.byteLength('skaists.bpay/1'));
  const head = Buffer.alloc(5); head[0] = 0x01; head.writeUInt32BE(bytes.length, 1);
  return Buffer.concat([MAGIC, Buffer.from([VERSION]), head, bytes, rest]);
};
const jsonIntent = (i) => ({
  domain: i.domain, nonce: i.nonce.toString('hex'), epoch: String(i.epoch), action: i.action.toString('hex'),
  destination: i.destination, capability: i.capability, amount: String(i.amount), expiry: String(i.expiry),
  payer: i.payer, payload: i.payload.toString('hex'),
});

const positives = [
  ['base', base()],
  ['astral destination', { ...base(), destination: 'vault:\uD83D\uDC1D' }],
  ['legitimate U+FFFD payer', { ...base(), payer: 'seat:\uFFFD' }],
  ['combining + latin extended', { ...base(), payer: 'seat:b\u0101bis\u0301' }],
  ['cjk capability', { ...base(), capability: '\u652f\u4ed8' }],
  ['astral domain', { ...base(), domain: 'skaists.\uD83D\uDC31/1' }],
  ['empty payload', { ...base(), payload: Buffer.alloc(0) }],
  ['u64 ceiling', { ...base(), amount: 18446744073709551615n }],
  ['u32 boundary +1', { ...base(), amount: 4294967296n }],
  ['nested envelope payload', { ...base(), payload: canonical(base()) }],
].map(([name, intent]) => {
  const env = canonical(intent);
  return { name, ...jsonIntent(intent), envelope: env.toString('hex'), length: env.length };
});

const refusals = [
  { name: 'domain lone high surrogate', code: 'bt-wb01:utf16', intent: jsonIntent({ ...base(), domain: '\uD800' }) },
  { name: 'destination lone low surrogate', code: 'bt-wb01:utf16', intent: jsonIntent({ ...base(), destination: '\uDC00' }) },
  { name: 'capability embedded surrogate', code: 'bt-wb01:utf16', intent: jsonIntent({ ...base(), capability: '\uD800A' }) },
  { name: 'payer embedded surrogate', code: 'bt-wb01:utf16', intent: jsonIntent({ ...base(), payer: 'x\uD801y' }) },
  { name: 'domain raw 0xff', code: 'bt-wb01:utf8', envelope: withDomainBytes(Buffer.from([0xff])).toString('hex') },
  { name: 'domain encoded surrogate (CESU-8)', code: 'bt-wb01:utf8', envelope: withDomainBytes(Buffer.from([0xed, 0xa0, 0x80])).toString('hex') },
  { name: 'domain overlong 0xc0 0x80', code: 'bt-wb01:utf8', envelope: withDomainBytes(Buffer.from([0xc0, 0x80])).toString('hex') },
  { name: 'domain beyond U+10FFFF', code: 'bt-wb01:utf8', envelope: withDomainBytes(Buffer.from([0xf4, 0x90, 0x80, 0x80])).toString('hex') },
  { name: 'domain truncated 0xc2', code: 'bt-wb01:utf8', envelope: withDomainBytes(Buffer.from([0xc2])).toString('hex') },
];

const doc = {
  // Kept on ONE line so the secret scan sees the PUBLIC-CONSTANT marker
  // beside every hex (the ant-pay-vector.json precedent): every value
  // here is a deterministic encoding of public test intents, no secret.
  what: 'PUBLIC-CONSTANT: deterministic bT-WB001 shared vectors — canonical encodings of public test intents and their refusal codes; generated by wb001-gen-vectors.mjs, never by hand.',
  format: 'bt-wb01/1',
  note: 'Pinned shared vectors — the bridge every implementation twin (Rust, Cryptol) must reproduce: positives byte-for-byte (full length, every meaningful byte), refusals by exact code. Includes the surrogate/invalid-UTF-8 boundary rows of the 2026-10-07 repair. Regenerate only via wb001-gen-vectors.mjs after an intentional format change.',
  positives,
  refusals,
};
writeFileSync(new URL('./wb001-vectors.json', import.meta.url), JSON.stringify(doc) + '\n');
console.log(`bT-WB001: vectors pinned 0 -> ${positives.length} positives, ${refusals.length} refusals (single line, PUBLIC-CONSTANT)`);

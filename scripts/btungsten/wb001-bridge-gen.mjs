// wb001-bridge-gen.mjs — regenerates wb001-bridge.json: the pinned
// byte-for-byte bridge between the runtime canonical() envelope and the
// Cryptol twin's `wire`, for the formal model's constructed terms.
//
// WHY THIS FILE EXISTS (founder review finding B1, 2026-10-07): the
// formal ladder proved `wireInjective` universally about the Cryptol
// wire, but NOTHING executable ever compared one Cryptol wire byte to
// one runtime canonical() byte — the twin's BRIDGE block was a comment.
// The deployed-wire proof claim cannot close on prose. This generator
// derives the bridge bytes FROM THE RUNTIME (wb001-intent.mjs
// canonical()), the .cry pins the same bytes as opaque constants, and
// two independent CI legs re-derive them every run:
//   - the node leg (wb001-bridge.test.mjs): canonical() == JSON bytes,
//     and the .cry carries each envelope's hex literal verbatim;
//   - the formal leg (wb001-formal-check.sh): :check evaluates each
//     .cry bridge property — prefix, zero tail, and envLen — exactly.
// Any drift on either side goes red. Sampled agreement on pinned
// terms, never universal equivalence (the result-class law).
//
// usage: node scripts/btungsten/wb001-bridge-gen.mjs [--check]
//   default: rewrite scripts/btungsten/wb001-bridge.json, print the
//            .cry constant block to paste into Intent.cry's bridge.
//   --check: re-derive, compare against the committed JSON, exit 1 on
//            drift (used by wb001-bridge.test.mjs which prints the
//            0->N line for CI's ratchet).

import { writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { canonical } from './wb001-intent.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const b32 = (seed) => { const b = Buffer.alloc(32); b.write(seed.slice(0, 24), 0, 'utf8'); return b; };

// The constructed terms, expressed as runtime intents. Field values are
// IDENTICAL to the closed terms in Intent.cry (iBase, twinL, twinR,
// astral, fffd, combining, nearA, nearB) — the JSON below is the
// cross-implementation statement of those same values.
const base = {
  domain: 'skaists.bpay/1',
  nonce: b32('nonce-wb001'),
  epoch: 1n,
  action: b32('action-hash-01'),
  destination: 'vault:0xBEEF',
  capability: 'pay',
  amount: 1000000n,
  expiry: 1790000000n,
  payer: 'seat:bFUzZ',
  payload: Buffer.from('{}', 'utf8'),
};
const TERMS = [
  { name: 'iBase', intent: base },
  { name: 'twinL', intent: { ...base, destination: 'ab', capability: 'c' } },
  { name: 'twinR', intent: { ...base, destination: 'a', capability: 'bc' } },
  { name: 'astral', intent: { ...base, domain: 'skaists.\u{1F41D}/1' } },           // 🐝 — 4-byte supplementary char, domain still 14 bytes
  { name: 'fffd', intent: { ...base, payer: '\uFFFD' } },                            // the honest U+FFFD: 3 bytes efbfbd
  { name: 'combining', intent: { ...base, destination: 'e\u0301' } },                // e + combining acute: 65 cc 81
  { name: 'nearA', intent: { ...base, payload: Buffer.from([0xde, 0xad, 0xbe, 0xef]) } },
  { name: 'nearB', intent: { ...base, payload: Buffer.from([0xde, 0xad, 0xbe, 0xef, 0x00]) } },
];

const jsonSafe = (intent) => {
  const o = {};
  for (const [k, v] of Object.entries(intent)) {
    o[k] = typeof v === 'bigint' ? v.toString() : Buffer.isBuffer(v) ? v.toString('hex') : v;
  }
  return o;
};

const derive = () => ({
  what: 'WB001 formal-wire bridge — runtime canonical() bytes pinned for the Cryptol twin\'s constructed terms (founder review B1)',
  format: 'each term carries the runtime intent (JSON-safe) and the exact canonical() envelope hex; Intent.cry pins the same hex as opaque constants; both CI legs re-derive every run',
  note: 'sampled agreement on pinned terms, never universal equivalence — the result-class law holds; regenerate with node scripts/btungsten/wb001-bridge-gen.mjs',
  terms: TERMS.map(({ name, intent }) => {
    const envelope = canonical(intent); // throws a typed Refusal if a term is not accepted — that itself would be a finding
    return { name, envLen: envelope.length, intent: jsonSafe(intent), envelopeHex: envelope.toString('hex') };
  }),
});

const block = (bridge) => {
  const lines = ['// ---- pinned runtime bytes (generated by wb001-bridge-gen.mjs; re-derived every CI run on BOTH legs) ----'];
  for (const t of bridge.terms) {
    lines.push(`b${t.name} : [${t.envLen}][8]`);
    lines.push(`b${t.name} = split (0x${t.envelopeHex} : [${8 * t.envLen}])  // PUBLIC-CONSTANT: runtime canonical() envelope of ${t.name}`);
  }
  return lines.join('\n');
};

const bridge = derive();
const path = join(here, 'wb001-bridge.json');

if (process.argv.includes('--check')) {
  const committed = JSON.parse(readFileSync(path, 'utf8'));
  const drift = JSON.stringify(committed.terms) !== JSON.stringify(bridge.terms);
  console.log(`bT-WB001-bridge: committed JSON vs runtime re-derive — ${drift ? 'DRIFT' : 'identical'} across ${bridge.terms.length} terms`);
  if (drift) { console.log('regenerate with: node scripts/btungsten/wb001-bridge-gen.mjs (and re-pin the .cry block)'); process.exit(1); }
} else {
  writeFileSync(path, JSON.stringify(bridge, null, 2) + '\n');
  console.error(`wrote ${path} (${bridge.terms.length} terms) — paste this block into Intent.cry's bridge:`);
  console.error(block(bridge));
}

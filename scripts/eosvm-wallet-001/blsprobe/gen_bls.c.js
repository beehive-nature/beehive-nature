// gen_bls.c.js — emit bls_const.h for the freestanding BLS probe: the G1
// generator and its double as 96-byte UNCOMPRESSED AFFINE LITTLE-ENDIAN
// (Spring v1.2.2 crypto.cpp format: fromAffineBytesLE non-Montgomery),
// generated from ffjavascript bls12-381 (G1.g is an LEM blob; convert via
// fromRprLEM / toRprUncompressed).
const fs = require('fs');
const path = require('path');
const { getCurveFromName } = require(path.join(process.env.HOME || '', 'eosvm001', 'oracle', 'node_modules', 'ffjavascript'));

async function main() {
  const curve = await getCurveFromName('bls12-381');
  const G1 = curve.G1;
  const gEl = G1.fromRprLEM(G1.g, 0);
  const g2El = G1.add(gEl, gEl);
  const q = BigInt(curve.q.toString());
  // toObject -> [x, y, z] plain bigints; serialize x||y as 48-byte LE each
  // (Spring v1.2.2 crypto.cpp fromAffineBytesLE non-Montgomery format)
  const le48 = (v) => { const b = new Uint8Array(48);
    for (let i = 0; i < 48; i++) b[i] = Number((v >> BigInt(8 * i)) & 0xffn); return b; };
  const enc = (el) => { const o = G1.toObject(el).map(BigInt);
    if (o[0] === 0n || o[0] >= q || o[1] >= q) throw new Error('coord out of field');
    return Buffer.concat([le48(o[0]), le48(o[1])]); };
  const p1 = enc(gEl), p2 = enc(g2El);
  const carray = (b) => Array.from(b).join(',');
  fs.writeFileSync(path.join(__dirname, 'bls_const.h'),
    `// bls_const.h — GENERATED by gen_bls.c.js (ffjavascript bls12-381). Do not edit.\n` +
    `static const unsigned char BLS_G1GEN_LE96[96] = {${carray(p1)}};\n` +
    `static const unsigned char BLS_2G1_LE96[96] = {${carray(p2)}};\n` +
    `// 2G1 hex (LE) for the receipt: ${Buffer.from(p2).toString('hex')} // PUBLIC-CONSTANT generated cross-check value\n`);
  console.log('bls_const.h written; 2G1(LE):', Buffer.from(p2).toString('hex').slice(0, 64) + '…');
  await curve.terminate();
}
main().catch(e => { console.error(e); process.exit(1); });

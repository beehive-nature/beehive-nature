// gen_bls.js — emit bls_gen.h: the BLS12-381 G1 generator as 96 bytes
// UNCOMPRESSED AFFINE LITTLE-ENDIAN (Spring v1.2.2 crypto.cpp format:
// x(48B LE) ‖ y(48B LE)), plus ffjavascript's 2*G1 for the off-chain check.
// WHERE it runs: WSL with ffjavascript at ~/eosvm001/oracle/node_modules.
const fs = require('fs');
const path = require('path');
const { getCurveFromName } = require(path.join(process.env.HOME || '', 'eosvm001', 'oracle', 'node_modules', 'ffjavascript'));

async function main() {
  const curve = await getCurveFromName('bls12-381');
  const F = curve.G1.F;
  const le = (el) => {                       // field element -> 48 LE bytes
    const v = BigInt(F.toObject(el));
    const b = Buffer.alloc(48);
    for (let i = 0; i < 48; i++) { b[i] = Number((v >> BigInt(8 * i)) & 0xffn); }
    return b;
  };
  const g = curve.G1.g;                      // projective; normalize
  const [x, y, z] = g;
  const inv = F.inv(z);
  const ax = F.mul(x, inv), ay = F.mul(y, inv);
  const p1 = Buffer.concat([le(ax), le(ay)]);          // G1 generator, 96B LE
  const g2p = curve.G1.add(g, g);                      // 2*G1 projective
  const [x2, y2, z2] = g2p;
  const inv2 = F.inv(z2);
  const p2 = Buffer.concat([le(F.mul(x2, inv2)), le(F.mul(y2, inv2))]);
  const bytes = (buf) => Array.from(buf).join(',');
  fs.writeFileSync(path.join(__dirname, 'bls_gen.h'),
    `// bls_gen.h — GENERATED by gen_bls.js (ffjavascript bls12-381). Do not edit.\n` +
    `#define BLS_G1GEN_LE96 {${bytes(p1)}}\n` +
    `// off-chain expected 2*G1 (96B LE, hex): ${p2.toString('hex')} // PUBLIC-CONSTANT generated cross-check value\n`);
  fs.writeFileSync(path.join(__dirname, 'expected_2g1.hex'), p2.toString('hex'));
  console.log('bls_gen.h written; expected 2G1:', p2.toString('hex'));
  await curve.terminate();
}
main().catch(e => { console.error(e); process.exit(1); });

#!/usr/bin/env python3
"""grid-gen.py — the generator half of the sampled-agreement check.

Reads the Rust binary's JSON lines and emits a Cryptol module whose cells
are EXACTLY those literals (one per executed cell:
(optIn, recs, rows, maxA, nextA, anyRow, gate)), plus the per-cell
agreement predicate against BnroseReplacement's own definitions and the
[9]-indexed theorem Cryptol proves. The generator is the only writer of
these modules; nobody hand-edits generated agreement.

With flip=1 it flips cell 0's gate literal — the perturbation control
that :prove MUST counterexample (the comparator's teeth).

usage: grid-gen.py <rust.json> <out.cry> <flip:0|1>
"""
import json
import sys

def cry(b: bool) -> str:
    return "True" if b else "False"

def rev16(mask: str) -> str:
    """The Rust half names attempt a as bit (1<<a) — LSB-offset. Cryptol
    sequences index from the MOST significant element, and the twin reads
    element a as attempt a. The generated literals therefore carry the
    Rust masks BIT-REVERSED, so both conventions say the same thing
    without touching either definition. (The grid exists precisely to
    catch seam disagreements like this one.)"""
    v = int(mask, 16)
    return f"0x{int(f'{v:016b}'[::-1], 2):04X}"

TPL = """// GENERATED by sampled-agreement-check.sh (grid-gen.py) from the Rust
// binary's own output — do not edit; the generator is the only writer.
// rustGrid holds one literal per executed cell
//   (optIn, recs, rows, maxA, nextA, anyRow, gate)
// padded to 512 (2^9) with a trivially-agreeing cell so the [9]-indexed
// theorem stays in range (gate True zero == True; maxAttempt zero == 0;
// nextAttempt zero == 1).
module {mod} where
import BnroseReplacement

rustGrid : [512](Bit, [16]Bit, [16]Bit, [4], [4], Bit, Bit)
rustGrid = [ {grid} ]

cellAgrees : (Bit, [16]Bit, [16]Bit, [4], [4], Bit, Bit) -> Bit
cellAgrees (o, r, w, ma, na, ar, g) =
     (gate o w == g)
  && (maxAttempt r == ma)
  && (nextAttempt r == na)
  && (anyRow w == ar)

gridCellAgrees : [9] -> Bit
gridCellAgrees i = cellAgrees (rustGrid @ i)

gridAllCellsAgree : Bit
gridAllCellsAgree = and [ cellAgrees c | c <- take`{{{n}}} rustGrid ]
"""

def main() -> None:
    rust_json, out_path, flip = sys.argv[1], sys.argv[2], sys.argv[3]
    cells = [json.loads(l) for l in open(rust_json, encoding="utf-8") if l.strip()]
    if flip == "1":
        cells[0]["gate"] = not cells[0]["gate"]  # the perturbation control
    rows = [f"({cry(c['optIn'])}, {rev16(c["recs"])}, {rev16(c["rows"])}, {c['maxA']}, {c['nextA']}, {cry(c['anyRow'])}, {cry(c['gate'])})" for c in cells]
    rows += ["(True, 0x0000, 0x0000, 0, 1, False, True)"] * (512 - len(rows))  # the agreeing pad
    grid = ", ".join(rows)
    mod = "GridRun" if flip == "0" else "GridBad"
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(TPL.format(mod=mod, n=len(cells), grid=grid))

if __name__ == "__main__":
    main()
